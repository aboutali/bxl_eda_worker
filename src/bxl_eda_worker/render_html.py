# Pages are rendered with links relative to docs/; archive copies live one
# level down, so _rebase_for_archive rewrites exactly these strings.
NAV_HTML = '<nav><a href="archive/">Archive →</a> · <a href="feed.xml">RSS</a></nav>'
_ARCHIVE_REBASE = (
    ('href="style.css"', 'href="../style.css"'),
    ('href="feed.xml"', 'href="../feed.xml"'),
    ('<a href="archive/">Archive →</a>', '<a href="../">← Latest</a> · <a href="./">Archive</a>'),
)


def render_html(
    items: list[Item],
    sources: list[Source],
    *,
    window_start: datetime,
    window_end: datetime,
    headline: str = "",
) -> str:
    by_id = {s.id: s for s in sources}
    n_collapsed = sum(1 for it in items if it.cluster_role == "secondary")
    items = [it for it in _dedupe_by_title(items) if it.cluster_role != "secondary"]
    # Relegate EEAS procedural statements in non-EU bodies (IAEA/OSCE/UN) to a
    # brief, content-less aside; keep them out of the main counts and sections.
    forum_items = [it for it in items if is_multilateral_forum_statement(it)]
    items = [it for it in items if not is_multilateral_forum_statement(it)]
    counts = {t: sum(1 for it in items if t in it.topics) for t in TOPIC_ORDER}
    n_swiss = sum(1 for it in items if it.swiss_relevance)

    date_str = window_end.strftime("%Y-%m-%d")
    parts: list[str] = [
        "<!DOCTYPE html>",
        "<html lang=\"en\">",
        "<head>",
        "<meta charset=\"utf-8\">",
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">",
        f"<title>EU FP Digest — {date_str}</title>",
        "<link rel=\"stylesheet\" href=\"style.css\">",
        "<link rel=\"alternate\" type=\"application/rss+xml\" title=\"EU FP Digest\" href=\"feed.xml\">",
        "</head>",
        "<body>",
        "<header>",
        "<h1>EU Foreign Policy &amp; Sanctions Digest</h1>",
        f"<div class=\"meta\">{date_str} · {_fmt(window_start)} → {_fmt(window_end)} UTC</div>",
        f"<div class=\"meta\">{len(items)} items"
        + (f" <span class=\"collapsed\">({n_collapsed} cross-source duplicates collapsed)</span>" if n_collapsed else "")
        + f" · Sanctions {counts['sanctions']} · Middle East {counts['middle_east']} · "
        f"FP {counts['foreign_policy']} · Swiss-relevance {n_swiss}</div>",
        NAV_HTML,
        "</header>",
        "<main>",
    ]

    if headline:
        parts.append("<section class=\"headline\">")
        parts.append("<h2>Today</h2>")
        parts.append(f"<p class=\"lede\">{html.escape(headline)}</p>")
        parts.append("</section>")

    if items:
        parts.append(_render_filter_bar(items))

    by_cat: dict[str, list[Item]] = defaultdict(list)
    for it in items:
        by_cat[it.category].append(it)

    for cat in CATEGORY_ORDER:
        cat_items = by_cat.get(cat, [])
        if not cat_items:
            continue
        parts.append(f"<section class=\"category cat-{html.escape(cat)}\">")
        parts.append(f"<h2>{html.escape(CATEGORY_LABELS[cat])}</h2>")
        for it in _sort_for_section(cat_items, by_id):
            parts.append(_render_item_html(it, by_id))
        parts.append("</section>")

    if forum_items:
        parts.append("<section class=\"forum-aside\">")
        parts.append("<h2>Multilateral-forum statements</h2>")
        parts.append(
            "<p class=\"forum-note\">EEAS interventions in non-EU bodies "
            "(IAEA, OSCE, UN) — listed for completeness, not the EU "
            "foreign-policy focus.</p>"
        )
        parts.append("<ul class=\"forum-list\">")
        for it in _sort_for_section(forum_items, by_id):
            parts.append(
                f"<li><a href=\"{html.escape(it.url, quote=True)}\">"
                f"{html.escape(it.title)}</a></li>"
            )
        parts.append("</ul>")
        parts.append("</section>")

    if not items and not forum_items:
        parts.append("<p class=\"empty\">No relevant items in this window.</p>")

    parts.append("</main>")
    polled = ", ".join(html.escape(s.name) for s in sources)
    parts.append(
        f"<footer>Generated by "
        f"<a href=\"https://github.com/aboutali/bxl_eda_worker\">bxl_eda_worker</a> · "
        f"sources polled: {polled}"
        f"<div class=\"made\">Made with &lt;3 for SER</div></footer>"
    )
    if items:
        parts.append(f"<script>{_FILTER_JS}</script>")
    parts.append("</body></html>")
    return "\n".join(parts)


def render_archive_index(entries: list[dict]) -> str:
    """`entries`: list of {slug, label, sort_date, n_items, n_swiss, kind}."""
    parts: list[str] = [
        "<!DOCTYPE html>",
        "<html lang=\"en\"><head>",
        "<meta charset=\"utf-8\">",
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">",
        "<title>EU FP Digest — Archive</title>",
        "<link rel=\"stylesheet\" href=\"../style.css\">",
        "</head><body>",
        "<header>",
        "<h1>Archive</h1>",
        "<nav><a href=\"../\">← Latest</a></nav>",
        "</header>",
        "<main><ul class=\"archive-list\">",
    ]
    for e in entries:
        kind_tag = (
            ' <span class="kind kind-weekly">weekly</span>' if e["kind"] == "weekly" else ""
        )
        parts.append(
            f"<li><a href=\"{html.escape(e['slug'])}.html\">{html.escape(e['label'])}</a>"
            f"{kind_tag}"
            f" <span class=\"meta\">{e['n_items']} items · {e['n_swiss']} Swiss-relevance</span></li>"
        )
    parts.append("</ul></main>")
    parts.append("</body></html>")
    return "\n".join(parts)


def write_html_outputs(
    content: str,
    *,
    date: datetime,
    docs_dir: Path = DOCS_DIR,
) -> tuple[Path, Path]:
    docs_dir.mkdir(parents=True, exist_ok=True)
    archive = docs_dir / "archive"
    archive.mkdir(parents=True, exist_ok=True)
    index_path = docs_dir / "index.html"
    archive_path = archive / f"{date.strftime('%Y-%m-%d')}.html"
    index_path.write_text(content, encoding="utf-8")
    archive_path.write_text(_rebase_for_archive(content), encoding="utf-8")
    return index_path, archive_path


def _rebase_for_archive(content: str) -> str:
    """Point docs/-relative links of a page one directory up (archive/)."""
    for old, new in _ARCHIVE_REBASE:
        content = content.replace(old, new)
    return content


def refresh_archive_index(
    docs_dir: Path = DOCS_DIR,
    *,
    extract_counts=None,
) -> Path:
    archive = docs_dir / "archive"
    archive.mkdir(parents=True, exist_ok=True)
    extract = extract_counts or _peek_counts

    daily_re = re.compile(r"^(20\d\d-\d\d-\d\d)$")
    weekly_re = re.compile(r"^(20\d\d)-W(\d\d)$")

    entries: list[dict] = []
    for f in archive.glob("*.html"):
        if f.name == "index.html":
            continue
        _heal_archive_links(f)
        slug = f.stem
        n_items, n_swiss = extract(f)
        if m := daily_re.match(slug):
            sort_date = date.fromisoformat(m.group(1))
            entries.append({
                "slug": slug, "label": slug, "sort_date": sort_date,
                "n_items": n_items, "n_swiss": n_swiss, "kind": "daily",
            })
        elif m := weekly_re.match(slug):
            year, week = int(m.group(1)), int(m.group(2))
            try:
                monday = date.fromisocalendar(year, week, 1)
                sunday = date.fromisocalendar(year, week, 7)
            except ValueError:
                continue
            entries.append({
                "slug": slug,
                "label": f"{slug} · {monday.strftime('%b %d')}–{sunday.strftime('%b %d')}",
                "sort_date": monday,
                "n_items": n_items, "n_swiss": n_swiss, "kind": "weekly",
            })
        # Anything else is ignored.

    entries.sort(key=lambda e: e["sort_date"], reverse=True)
    out = archive / "index.html"
    out.write_text(render_archive_index(entries), encoding="utf-8")
    write_feed(docs_dir)
    return out


def _heal_archive_links(path: Path) -> None:
    """Older archive pages (and seed-archive weeks) carry docs/-relative links."""
    text = path.read_text(encoding="utf-8")
    if 'href="style.css"' in text:
        path.write_text(_rebase_for_archive(text), encoding="utf-8")


def write_feed(docs_dir: Path = DOCS_DIR, *, site_url: str = SITE_URL) -> Path:
    """RSS 2.0 feed with one entry per daily digest (newest FEED_DAYS days)."""
    daily = sorted(
        (f for f in (docs_dir / "archive").glob("20??-??-??.html")),
        key=lambda f: f.stem, reverse=True,
    )[:FEED_DAYS]
    entries: list[str] = []
    for f in daily:
        text = f.read_text(encoding="utf-8")
        n_items, n_swiss = _peek_counts(f)
        m_lede = re.search(r'<p class="lede">(.*?)</p>', text, re.S)
        lede = html.unescape(m_lede.group(1)).strip() if m_lede else ""
        m_end = re.search(r"→ (\d{4}-\d\d-\d\d \d\d:\d\d) UTC", text)
        when = (
            datetime.strptime(m_end.group(1), "%Y-%m-%d %H:%M")
            if m_end else datetime.fromisoformat(f.stem)
        ).replace(tzinfo=timezone.utc)
        link = f"{site_url}archive/{f.stem}.html"
        summary = lede or f"{n_items} items, {n_swiss} Swiss-relevant."
        entries.append(
            "<item>"
            f"<title>EU FP Digest — {f.stem} ({n_items} items)</title>"
            f"<link>{xml_escape(link)}</link>"
            f'<guid isPermaLink="true">{xml_escape(link)}</guid>'
            f"<pubDate>{format_datetime(when)}</pubDate>"
            f"<description>{xml_escape(summary)}</description>"
            "</item>"
        )
    feed = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<rss version="2.0"><channel>'
        "<title>EU Foreign Policy &amp; Sanctions Digest</title>"
        f"<link>{xml_escape(site_url)}</link>"
        "<description>Daily digest of EU foreign-policy, Middle East and sanctions "
        "developments, framed for a Swiss reader.</description>"
        "<language>en</language>"
        + "".join(entries)
        + "</channel></rss>\n"
    )
    out = docs_dir / "feed.xml"
    out.write_text(feed, encoding="utf-8")
    return out


def _peek_counts(path: Path) -> tuple[int, int]:
    text = path.read_text(encoding="utf-8")
    m_items = re.search(r"(\d+) items", text)
    m_swiss = re.search(r"Swiss-relevance (\d+)", text)
    return (
        int(m_items.group(1)) if m_items else 0,
        int(m_swiss.group(1)) if m_swiss else 0,
    )


def _render_item_html(it: Item, by_id: dict[str, Source]) -> str:
    when = it.published_at or it.fetched_at
    src = by_id.get(it.source)
    source_name = src.name if src else it.source
    badge = f" <span class=\"badge\">{html.escape(src.badge)}</span>" if (src and src.badge) else ""
    lang = (
        f" <span class=\"lang\">{html.escape(it.language)}</span>"
        if (it.language and it.language != "en")
        else ""
    )
    importance = (
        f" <span class=\"importance\" title=\"importance {it.importance}/5\">{'★' * it.importance}</span>"
        if it.importance >= 4 else ""
    )

    title = html.escape(it.title)
    url = html.escape(it.url, quote=True)

    summary_text = it.summary_oneliner or it.summary
    summary = (
        f"<p class=\"summary\">{html.escape(summary_text)}</p>" if summary_text else ""
    )

    tags: list[str] = []
    if it.swiss_relevance:
        if it.swiss_rationale:
            tags.append(
                f"<span class=\"tag-seco\">🇨🇭 {html.escape(it.swiss_rationale)}</span>"
            )
        elif "sanctions" in it.topics:
            tags.append("<span class=\"tag-seco\">🇨🇭 SECO alignment likely</span>")
        else:
            tags.append("<span class=\"tag-seco\">🇨🇭 Swiss-relevant</span>")
    topic_chips = " ".join(
        f"<span class=\"topic\">{html.escape(TOPIC_TAG_LABELS[t])}</span>"
        for t in TOPIC_ORDER
        if t in it.topics
    )
    if topic_chips:
        tags.append(topic_chips)
    if it.regions:
        tags.append("regions: " + html.escape(", ".join(it.regions)))
    tags_html = (
        f"<div class=\"tags\">{' · '.join(tags)}</div>" if tags else ""
    )

    peers_html = ""
    if it.cluster_peers:
        peer_links = []
        for peer in it.cluster_peers:
            peer_src = by_id.get(peer.get("source", ""))
            peer_name = peer_src.name if peer_src else peer.get("source", "")
            peer_url = html.escape(peer.get("url", ""), quote=True)
            peer_links.append(
                f"<a href=\"{peer_url}\">{html.escape(peer_name)}</a>"
            )
        peers_html = (
            f"<div class=\"also-covered\">also covered: {', '.join(peer_links)}</div>"
        )

    data = (
        f" data-topics=\"{html.escape(' '.join(it.topics), quote=True)}\""
        f" data-regions=\"{html.escape('|'.join(_norm_regions(it)), quote=True)}\""
        f" data-swiss=\"{'1' if it.swiss_relevance else '0'}\""
    )
    return (
        f"<article{data}>"
        f"<h4><a href=\"{url}\">{title}</a></h4>"
        f"<div class=\"src\">{html.escape(source_name)}{badge}{lang}{importance}"
        f" · <time datetime=\"{when.isoformat()}\">{_fmt(when)}</time></div>"
        f"{summary}{tags_html}{peers_html}"
        "</article>"
    )


def _fmt(dt: datetime) -> str:
    return dt.strftime("%Y-%m-%d %H:%M")


# Region labels come from the LLM ("saudi_arabia", "usa"); fold the variants.
_REGION_ALIASES = {"usa": "united states", "us": "united states", "uk": "united kingdom"}
MAX_REGION_FILTERS = 8


def _norm_regions(it: Item) -> list[str]:
    out: list[str] = []
    for r in it.regions:
        r = " ".join(r.replace("_", " ").lower().split())
        r = _REGION_ALIASES.get(r, r)
        if r and r not in out:
            out.append(r)
    return out


def _render_filter_bar(items: list[Item]) -> str:
    """Filter buttons for the topics/regions on this page. Hidden until JS runs."""
    buttons = ['<button type="button" data-filter="all">All</button>']
    for t in TOPIC_ORDER:
        if any(t in it.topics for it in items):
            buttons.append(
                f'<button type="button" data-filter="topic:{t}">{html.escape(TOPIC_TAG_LABELS[t])}</button>'
            )
    if any(it.swiss_relevance for it in items):
        buttons.append('<button type="button" data-filter="swiss">🇨🇭 Swiss</button>')
    region_counts = Counter(r for it in items for r in _norm_regions(it))
    for region, n in region_counts.most_common(MAX_REGION_FILTERS):
        if n < 2:
            break
        buttons.append(
            f'<button type="button" data-filter="region:{html.escape(region, quote=True)}">'
            f"{html.escape(region.title())}</button>"
        )
    return (
        '<div class="filters" role="group" aria-label="Filter items" hidden>'
        + "".join(buttons)
        + "</div>"
    )


